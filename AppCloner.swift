// AppCloner — macOS App 分身工具（微信 / QQ / 企业微信 / 任意 App）
// 原理：复制原版 App → 修改 Bundle ID → ad-hoc 重新签名
// 系统把分身当成另一个独立 App，可同时运行，数据互相隔离。
// 支持 Apple Silicon（M1/M2/M3/M4…）与 Intel，macOS 13+

import SwiftUI
import AppKit
import UniformTypeIdentifiers

// MARK: - 常量

let kSourcePath = "AppClonerSourcePath"
let kSourceVersion = "AppClonerSourceVersion"
let kIndex = "AppClonerIndex"
let cloneDir = FileManager.default.homeDirectoryForCurrentUser
    .appendingPathComponent("Applications/AppClones", isDirectory: true)
let lsregister = "/System/Library/Frameworks/CoreServices.framework/Frameworks/LaunchServices.framework/Support/lsregister"

/// 本地化字符串：读取 Resources/<语言>.lproj/Localizable.strings，跟随系统语言，缺省为英文
func L(_ key: String, _ args: CVarArg...) -> String {
    let format = NSLocalizedString(key, comment: "")
    return args.isEmpty ? format : String(format: format, arguments: args)
}

// MARK: - 模型

struct CloneInfo: Identifiable {
    let url: URL
    var id: String { url.path }
    let name: String
    let bundleID: String
    let index: Int
    let sourceURL: URL
    let clonedVersion: String

    var sourceMissing: Bool { !FileManager.default.fileExists(atPath: sourceURL.path) }
    var needsRebuild: Bool {
        guard let v = Cloner.version(of: sourceURL) else { return false }
        return v != clonedVersion
    }
    var isRunning: Bool { !NSRunningApplication.runningApplications(withBundleIdentifier: bundleID).isEmpty }
}

enum ClonerError: LocalizedError {
    case message(String)
    var errorDescription: String? {
        switch self { case .message(let m): return m }
    }
}

// MARK: - 核心逻辑

enum Cloner {
    final class Box { var data = Data() }

    @discardableResult
    static func run(_ tool: String, _ args: [String]) throws -> String {
        let p = Process()
        p.executableURL = URL(fileURLWithPath: tool)
        p.arguments = args
        let outPipe = Pipe(), errPipe = Pipe()
        p.standardOutput = outPipe
        p.standardError = errPipe
        try p.run()
        // 并行读 stderr，避免输出很多时（如 codesign --deep）管道写满导致卡死
        let errBox = Box()
        let group = DispatchGroup()
        group.enter()
        DispatchQueue.global().async {
            errBox.data = errPipe.fileHandleForReading.readDataToEndOfFile()
            group.leave()
        }
        let outData = outPipe.fileHandleForReading.readDataToEndOfFile()
        group.wait()
        p.waitUntilExit()
        let out = String(decoding: outData, as: UTF8.self)
        guard p.terminationStatus == 0 else {
            let err = String(decoding: errBox.data, as: UTF8.self)
            let name = (tool as NSString).lastPathComponent
            throw ClonerError.message(L("run.failed", name, p.terminationStatus, out + err))
        }
        return out
    }

    static func infoPlistURL(_ app: URL) -> URL { app.appendingPathComponent("Contents/Info.plist") }

    static func readInfo(_ app: URL) -> [String: Any]? {
        guard let data = try? Data(contentsOf: infoPlistURL(app)) else { return nil }
        return (try? PropertyListSerialization.propertyList(from: data, format: nil)) as? [String: Any]
    }

    static func writeInfo(_ info: [String: Any], to app: URL) throws {
        let data = try PropertyListSerialization.data(fromPropertyList: info, format: .xml, options: 0)
        try data.write(to: infoPlistURL(app), options: .atomic)
    }

    static func version(of app: URL) -> String? {
        guard let i = readInfo(app) else { return nil }
        let short = i["CFBundleShortVersionString"] as? String ?? "?"
        let build = i["CFBundleVersion"] as? String ?? "?"
        return "\(short) (\(build))"
    }

    static func displayName(of app: URL) -> String {
        let n = FileManager.default.displayName(atPath: app.path)
        return n.hasSuffix(".app") ? String(n.dropLast(4)) : n
    }

    // MARK: Electron 支持

    static func isElectron(_ app: URL) -> Bool {
        FileManager.default.fileExists(
            atPath: app.appendingPathComponent("Contents/Frameworks/Electron Framework.framework").path)
    }

    /// Electron App 的数据目录由 App 名称决定（不看 Bundle ID），分身会和原版共用
    /// ~/Library/Application Support/<名称>，抢同一份数据库 / 单实例锁，导致闪退。
    /// 这里放一个启动脚本作为分身的主程序，用 --user-data-dir 给分身独立的数据目录。
    /// 真正的可执行文件名保持不变（Electron 靠它找 "<名称> Helper.app"）。
    static func installElectronLauncher(in app: URL, realExecutable: String, userDataDir: String) throws -> String {
        let launcherName = realExecutable + " Launcher"
        let url = app.appendingPathComponent("Contents/MacOS/" + launcherName)
        let script = """
        #!/bin/bash
        # Generated by AppCloner: gives this Electron clone its own data directory
        DIR="$(cd "$(dirname "$0")" && pwd)"
        exec "$DIR/\(realExecutable)" --user-data-dir="$HOME/Library/Application Support/\(userDataDir)" "$@"

        """
        try script.write(to: url, atomically: true, encoding: .utf8)
        try FileManager.default.setAttributes([.posixPermissions: 0o755], ofItemAtPath: url.path)
        return launcherName
    }

    // MARK: 签名

    /// ad-hoc 签名不能带这些受限 entitlements，带了会被系统直接拒绝启动
    static let restrictedEntitlementPrefixes = [
        "com.apple.developer.", "com.apple.application-identifier", "application-identifier",
        "keychain-access-groups", "com.apple.security.application-groups",
    ]

    /// 读取代码的 entitlements，并去掉受限项；没有则返回 nil
    static func entitlements(of url: URL) -> [String: Any]? {
        guard let xml = try? run("/usr/bin/codesign", ["-d", "--entitlements", "-", "--xml", url.path]) else { return nil }
        let trimmed = xml.trimmingCharacters(in: .whitespacesAndNewlines.union(CharacterSet(charactersIn: "\u{0}")))
        guard !trimmed.isEmpty, let data = trimmed.data(using: .utf8),
              let ent = (try? PropertyListSerialization.propertyList(from: data, format: nil)) as? [String: Any]
        else { return nil }
        let kept = ent.filter { key, _ in !restrictedEntitlementPrefixes.contains { key.hasPrefix($0) } }
        return kept.isEmpty ? nil : kept
    }

    static func isMachO(_ file: URL) -> Bool {
        guard let h = try? FileHandle(forReadingFrom: file) else { return false }
        defer { try? h.close() }
        guard let d = try? h.read(upToCount: 4), d.count == 4 else { return false }
        let b = Array(d)
        let m = UInt32(b[0]) << 24 | UInt32(b[1]) << 16 | UInt32(b[2]) << 8 | UInt32(b[3])
        return [0xfeedface, 0xfeedfacf, 0xcefaedfe, 0xcffaedfe, 0xcafebabe, 0xbebafeca].contains(m)
    }

    static func isBundleMainExecutable(_ file: URL) -> Bool {
        let macos = file.deletingLastPathComponent()
        let contents = macos.deletingLastPathComponent()
        guard macos.lastPathComponent == "MacOS", contents.lastPathComponent == "Contents" else { return false }
        return (readInfo(contents.deletingLastPathComponent())?["CFBundleExecutable"] as? String) == file.lastPathComponent
    }

    /// 先整体 ad-hoc 签名，再把原版里每段代码的 entitlements（去掉受限项）重新签回去，
    /// 由内到外，最后重签主 App。--deep 配 --entitlements 会把主程序的 entitlements 错误地套到所有 Helper 上，所以要逐个签。
    static func sign(clone: URL, source: URL, keepEntitlements: Bool, movedMainExecutable: String?,
                     log: (String) -> Void) throws {
        try run("/usr/bin/codesign", ["--force", "--deep", "--sign", "-", clone.path])

        let fm = FileManager.default
        let bundleExts: Set<String> = ["app", "framework", "xpc", "appex", "bundle", "plugin"]
        var entMap: [String: [String: Any]] = [:]   // 相对 App 根目录的路径 → entitlements（"" 表示主 App）
        var targets: Set<String> = [""]

        if keepEntitlements {
            log(L("log.readEntitlements"))
            if let e = entitlements(of: source) { entMap[""] = e }
            let keys: [URLResourceKey] = [.isRegularFileKey, .isDirectoryKey, .isSymbolicLinkKey]
            let en = fm.enumerator(at: source.appendingPathComponent("Contents"), includingPropertiesForKeys: keys)
            while let u = en?.nextObject() as? URL {
                guard let v = try? u.resourceValues(forKeys: Set(keys)), v.isSymbolicLink != true else { continue }
                let isCandidate: Bool
                if v.isDirectory == true {
                    isCandidate = ["app", "xpc", "appex"].contains(u.pathExtension)
                } else {
                    isCandidate = v.isRegularFile == true && isMachO(u) && !isBundleMainExecutable(u)
                }
                if isCandidate, let e = entitlements(of: u) {
                    entMap[String(u.path.dropFirst(source.path.count + 1))] = e
                }
            }
        }

        // 主程序被换成启动脚本时，原主程序的 entitlements 跟着真正的可执行文件走
        if let exe = movedMainExecutable {
            let rel = "Contents/MacOS/" + exe
            if let e = entMap.removeValue(forKey: "") { entMap[rel] = e }
            targets.insert(rel)
        }

        // 内层重签后，外层所有 bundle 的封印都要更新
        for k in Set(entMap.keys).union(targets) where !k.isEmpty {
            targets.insert(k)
            var comps = k.split(separator: "/").map(String.init)
            while comps.count > 1 {
                comps.removeLast()
                if bundleExts.contains((comps.last! as NSString).pathExtension) {
                    targets.insert(comps.joined(separator: "/"))
                }
            }
        }

        let ordered = targets.sorted {
            let a = $0.split(separator: "/").count, b = $1.split(separator: "/").count
            return a != b ? a > b : $0 < $1
        }
        let entDir = fm.temporaryDirectory.appendingPathComponent("appcloner-\(UUID().uuidString)")
        try fm.createDirectory(at: entDir, withIntermediateDirectories: true)
        defer { try? fm.removeItem(at: entDir) }

        for (i, rel) in ordered.enumerated() {
            var args = ["--force", "--sign", "-"]
            if let e = entMap[rel] {
                let f = entDir.appendingPathComponent("\(i).plist")
                try PropertyListSerialization.data(fromPropertyList: e, format: .xml, options: 0).write(to: f)
                args += ["--entitlements", f.path]
                log(L("log.keepEntitlements", rel.isEmpty ? L("log.mainExecutable") : rel))
            }
            args.append(rel.isEmpty ? clone.path : clone.appendingPathComponent(rel).path)
            try run("/usr/bin/codesign", args)
        }
    }

    static func listClones() -> [CloneInfo] {
        guard let items = try? FileManager.default.contentsOfDirectory(
            at: cloneDir, includingPropertiesForKeys: nil, options: [.skipsHiddenFiles]) else { return [] }
        return items.filter { $0.pathExtension == "app" }.compactMap { url -> CloneInfo? in
            guard let i = readInfo(url),
                  let src = i[kSourcePath] as? String,
                  let bid = i["CFBundleIdentifier"] as? String else { return nil }
            return CloneInfo(url: url,
                             name: url.deletingPathExtension().lastPathComponent,
                             bundleID: bid,
                             index: i[kIndex] as? Int ?? 0,
                             sourceURL: URL(fileURLWithPath: src),
                             clonedVersion: i[kSourceVersion] as? String ?? "")
        }.sorted { $0.name.localizedStandardCompare($1.name) == .orderedAscending }
    }

    /// 同一个原版 App 的下一个可用编号（从 2 开始）
    static func nextIndex(for sourceID: String, existing: [CloneInfo]) -> Int {
        let used = Set(existing.filter { $0.bundleID.hasPrefix(sourceID + ".clone") }.map(\.index))
        var n = 2
        while used.contains(n) { n += 1 }
        return n
    }

    static func makeClone(source: URL, name: String, index: Int, keepEntitlements: Bool,
                          log: @escaping (String) -> Void) throws {
        guard let srcInfo = readInfo(source), let srcID = srcInfo["CFBundleIdentifier"] as? String else {
            throw ClonerError.message(L("err.invalidApp"))
        }
        if srcInfo[kSourcePath] != nil {
            throw ClonerError.message(L("err.cloneOfClone"))
        }
        let safeName = name.replacingOccurrences(of: "/", with: "-").trimmingCharacters(in: .whitespaces)
        guard !safeName.isEmpty else { throw ClonerError.message(L("err.emptyName")) }

        let fm = FileManager.default
        try fm.createDirectory(at: cloneDir, withIntermediateDirectories: true)
        let dest = cloneDir.appendingPathComponent(safeName + ".app")
        let tmp = cloneDir.appendingPathComponent(".\(UUID().uuidString).app")
        let newID = "\(srcID).clone\(index)"

        log(L("log.copy", source.lastPathComponent))
        try run("/usr/bin/ditto", [source.path, tmp.path])
        do {
            log(L("log.bundleID", srcID, newID))
            var info = readInfo(tmp) ?? srcInfo
            info["CFBundleIdentifier"] = newID
            // Electron 用 CFBundleName 拼出 "<名称> Helper.app" 的路径，改了会报
            // "Unable to find helper app" 并闪退，所以 Electron App 只改显示名称
            if !isElectron(tmp) { info["CFBundleName"] = safeName }
            info["CFBundleDisplayName"] = safeName
            info[kSourcePath] = source.path
            info[kSourceVersion] = version(of: source) ?? ""
            info[kIndex] = index
            info["SUEnableAutomaticChecks"] = false // 分身不自己更新，原版更新后点「重建」
            var movedExe: String?
            if isElectron(tmp), let exe = info["CFBundleExecutable"] as? String {
                log(L("log.electron", newID))
                info["CFBundleExecutable"] = try installElectronLauncher(in: tmp, realExecutable: exe, userDataDir: newID)
                movedExe = exe
            }
            try writeInfo(info, to: tmp)

            log(L("log.quarantine"))
            _ = try? run("/usr/bin/xattr", ["-cr", tmp.path])

            // Apple Silicon 上所有 arm64 代码必须有签名，改了 Info.plist 后原签名失效，
            // 所以这里用 ad-hoc 签名（"-"）重新签整个 bundle，Intel 同样适用。
            log(L("log.sign"))
            try sign(clone: tmp, source: source, keepEntitlements: keepEntitlements,
                     movedMainExecutable: movedExe, log: log)

            if fm.fileExists(atPath: dest.path) { try fm.removeItem(at: dest) }
            try fm.moveItem(at: tmp, to: dest)
        } catch {
            try? fm.removeItem(at: tmp)
            throw error
        }

        log(L("log.register"))
        _ = try? run(lsregister, ["-f", dest.path])
        log(L("log.done", dest.path))
    }
}

// MARK: - ViewModel

@MainActor
final class AppModel: ObservableObject {
    @Published var source: URL?
    @Published var cloneName = ""
    @Published var keepEntitlements = true
    @Published var clones: [CloneInfo] = []
    @Published var log: [String] = []
    @Published var errorText: String?
    @Published var busy = false

    init() { refresh() }

    func refresh() { clones = Cloner.listClones() }

    func choose(_ url: URL) {
        guard url.pathExtension == "app" else { errorText = L("err.notApp"); return }
        errorText = nil
        source = url
        let base = Cloner.displayName(of: url)
        if let id = Cloner.readInfo(url)?["CFBundleIdentifier"] as? String {
            cloneName = "\(base) \(Cloner.nextIndex(for: id, existing: clones))"
        } else {
            cloneName = "\(base) 2"
        }
    }

    func pickWithPanel() {
        let panel = NSOpenPanel()
        panel.directoryURL = URL(fileURLWithPath: "/Applications")
        panel.allowedContentTypes = [.application]
        panel.allowsMultipleSelection = false
        panel.prompt = L("panel.choose")
        if panel.runModal() == .OK, let url = panel.url { choose(url) }
    }

    func createClone() {
        guard let src = source,
              let id = Cloner.readInfo(src)?["CFBundleIdentifier"] as? String else { return }
        let name = cloneName.trimmingCharacters(in: .whitespaces)
        if clones.contains(where: { $0.name == name }) {
            errorText = L("err.duplicateName", name)
            return
        }
        perform(source: src, name: name, index: Cloner.nextIndex(for: id, existing: clones))
    }

    func rebuild(_ c: CloneInfo) {
        if c.isRunning { errorText = L("err.quitBeforeRebuild", c.name); return }
        perform(source: c.sourceURL, name: c.name, index: c.index)
    }

    func launch(_ c: CloneInfo) {
        NSWorkspace.shared.openApplication(at: c.url, configuration: NSWorkspace.OpenConfiguration()) { _, err in
            if let err {
                let msg = L("err.launchFailed", err.localizedDescription)
                Task { @MainActor in self.errorText = msg }
            }
        }
    }

    func reveal(_ url: URL) { NSWorkspace.shared.activateFileViewerSelecting([url]) }

    func openCloneFolder() {
        try? FileManager.default.createDirectory(at: cloneDir, withIntermediateDirectories: true)
        NSWorkspace.shared.open(cloneDir)
    }

    func delete(_ c: CloneInfo) {
        if c.isRunning { errorText = L("err.quitBeforeDelete", c.name); return }
        let alert = NSAlert()
        alert.messageText = L("alert.deleteTitle", c.name)
        alert.informativeText = L("alert.deleteInfo")
        alert.addButton(withTitle: L("alert.delete"))
        alert.addButton(withTitle: L("alert.cancel"))
        guard alert.runModal() == .alertFirstButtonReturn else { return }
        NSWorkspace.shared.recycle([c.url]) { _, _ in
            Task { @MainActor in self.refresh() }
        }
    }

    private func perform(source: URL, name: String, index: Int) {
        busy = true
        log = []
        errorText = nil
        let keep = keepEntitlements
        Task.detached {
            do {
                try Cloner.makeClone(source: source, name: name, index: index, keepEntitlements: keep) { line in
                    Task { @MainActor in self.log.append(line) }
                }
            } catch {
                var msg = error.localizedDescription
                if msg.contains("Operation not permitted") || msg.contains("Permission denied") {
                    msg += L("err.permissionHint")
                }
                let finalMsg = msg
                await MainActor.run { self.errorText = finalMsg }
            }
            await MainActor.run {
                self.busy = false
                self.refresh()
            }
        }
    }
}

// MARK: - 界面

@main
struct AppClonerApp: App {
    @StateObject private var model = AppModel()
    var body: some Scene {
        WindowGroup(L("window.title")) {
            ContentView()
                .environmentObject(model)
                .frame(minWidth: 640, minHeight: 560)
        }
        .windowResizability(.contentMinSize)
    }
}

struct AppIcon: View {
    let url: URL?
    let size: CGFloat
    var body: some View {
        Group {
            if let url {
                Image(nsImage: NSWorkspace.shared.icon(forFile: url.path)).resizable()
            } else {
                Image(systemName: "square.dashed").resizable().foregroundStyle(.secondary)
            }
        }
        .frame(width: size, height: size)
    }
}

struct ContentView: View {
    @EnvironmentObject var model: AppModel
    @State private var dropTargeted = false

    var body: some View {
        VStack(alignment: .leading, spacing: 16) {
            GroupBox(L("section.new")) {
                VStack(alignment: .leading, spacing: 12) {
                    HStack(spacing: 12) {
                        AppIcon(url: model.source, size: 48)
                        VStack(alignment: .leading, spacing: 2) {
                            Text(model.source.map { Cloner.displayName(of: $0) } ?? L("drop.placeholder"))
                                .font(.headline)
                            if let s = model.source {
                                Text(s.path).font(.caption).foregroundStyle(.secondary)
                            }
                        }
                        Spacer()
                        Button(L("button.chooseApp")) { model.pickWithPanel() }
                    }
                    .padding(10)
                    .background(
                        RoundedRectangle(cornerRadius: 8)
                            .strokeBorder(dropTargeted ? Color.accentColor : Color.secondary.opacity(0.35),
                                          style: StrokeStyle(lineWidth: 1.5, dash: [5]))
                    )
                    .onDrop(of: [.fileURL], isTargeted: $dropTargeted) { providers in
                        guard let p = providers.first else { return false }
                        _ = p.loadObject(ofClass: URL.self) { url, _ in
                            if let url { Task { @MainActor in model.choose(url) } }
                        }
                        return true
                    }

                    HStack {
                        Text(L("label.cloneName"))
                        TextField(L("placeholder.cloneName"), text: $model.cloneName)
                            .textFieldStyle(.roundedBorder)
                        Button(L("button.create")) { model.createClone() }
                            .keyboardShortcut(.defaultAction)
                            .disabled(model.source == nil || model.busy
                                      || model.cloneName.trimmingCharacters(in: .whitespaces).isEmpty)
                    }

                    Toggle(L("toggle.keepEntitlements"),
                           isOn: $model.keepEntitlements)
                        .font(.caption)
                }
                .padding(4)
            }

            GroupBox {
                if model.clones.isEmpty {
                    Text(L("empty.clones")).foregroundStyle(.secondary)
                        .frame(maxWidth: .infinity, minHeight: 100)
                } else {
                    List(model.clones) { c in CloneRow(clone: c) }
                        .listStyle(.inset)
                        .frame(minHeight: 180)
                }
            } label: {
                HStack {
                    Text(L("section.clones", model.clones.count))
                    Spacer()
                    Button(L("button.refresh")) { model.refresh() }.buttonStyle(.link)
                    Button(L("button.openFolder")) { model.openCloneFolder() }.buttonStyle(.link)
                }
            }

            if model.busy || !model.log.isEmpty || model.errorText != nil {
                GroupBox(model.busy ? L("section.working") : L("section.log")) {
                    ScrollView {
                        VStack(alignment: .leading, spacing: 3) {
                            ForEach(Array(model.log.enumerated()), id: \.offset) { item in
                                Text(item.element)
                            }
                            if let e = model.errorText {
                                Text(e).foregroundStyle(.red)
                            }
                        }
                        .font(.system(.caption, design: .monospaced))
                        .textSelection(.enabled)
                        .frame(maxWidth: .infinity, alignment: .leading)
                    }
                    .frame(height: 110)
                }
            }
        }
        .padding(20)
    }
}

struct CloneRow: View {
    @EnvironmentObject var model: AppModel
    let clone: CloneInfo

    var body: some View {
        HStack(spacing: 10) {
            AppIcon(url: clone.url, size: 32)
            VStack(alignment: .leading, spacing: 2) {
                Text(clone.name).font(.body.weight(.medium))
                Text(clone.bundleID).font(.caption).foregroundStyle(.secondary)
                if clone.sourceMissing {
                    Label(L("status.sourceMissing"), systemImage: "exclamationmark.triangle")
                        .font(.caption).foregroundStyle(.red)
                } else if clone.needsRebuild {
                    Label(L("status.needsRebuild"), systemImage: "arrow.triangle.2.circlepath")
                        .font(.caption).foregroundStyle(.orange)
                }
            }
            Spacer()
            Button(L("button.launch")) { model.launch(clone) }
            Button(L("button.rebuild")) { model.rebuild(clone) }
                .disabled(model.busy || clone.sourceMissing)
            Menu {
                Button(L("menu.showInFinder")) { model.reveal(clone.url) }
                Divider()
                Button(L("menu.delete"), role: .destructive) { model.delete(clone) }
            } label: {
                Image(systemName: "ellipsis.circle")
            }
            .menuStyle(.borderlessButton)
            .fixedSize()
        }
        .padding(.vertical, 4)
    }
}
